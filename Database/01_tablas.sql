CREATE TABLE usuarios (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario VARCHAR2(60) NOT NULL UNIQUE,
    password_hash VARCHAR2(500) NOT NULL,
    activo CHAR(1) DEFAULT 'S' NOT NULL
        CHECK (activo IN ('S','N')),
    fecha_creacion TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE clientes_a (
    id_cliente NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR2(100) NOT NULL,
    apellidos VARCHAR2(100) NOT NULL,
    correo VARCHAR2(150) NOT NULL UNIQUE,
    telefono VARCHAR2(30),
    fecha_registro TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_clientes_a_correo CHECK (INSTR(correo, '@') > 1)
);

CREATE INDEX ix_clientes_a_nombre ON clientes_a(apellidos, nombres);

COMMIT;